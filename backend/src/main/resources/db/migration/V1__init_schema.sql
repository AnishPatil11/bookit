-- Portable schema (PostgreSQL and H2 in PostgreSQL mode).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(255)  NOT NULL,
    password_hash VARCHAR(255)  NOT NULL,
    role          VARCHAR(20)   NOT NULL,
    created_at    TIMESTAMP     NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE restaurants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    description VARCHAR(1000),
    cuisine     VARCHAR(60)   NOT NULL,
    address     VARCHAR(200),
    city        VARCHAR(80)   NOT NULL,
    open_time   TIME          NOT NULL,
    close_time  TIME          NOT NULL,
    image_url   VARCHAR(500),
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP     NOT NULL
);

CREATE TABLE dining_tables (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT      NOT NULL REFERENCES restaurants (id),
    label         VARCHAR(40) NOT NULL,
    capacity      INT         NOT NULL,
    active        BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_dining_tables_label UNIQUE (restaurant_id, label)
);

CREATE TABLE menu_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT        NOT NULL REFERENCES restaurants (id),
    name          VARCHAR(120)  NOT NULL,
    description   VARCHAR(500),
    category      VARCHAR(60)   NOT NULL,
    price         NUMERIC(10,2) NOT NULL,
    available     BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE bookings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    restaurant_id   BIGINT      NOT NULL REFERENCES restaurants (id),
    dining_table_id BIGINT      NOT NULL REFERENCES dining_tables (id),
    starts_at       TIMESTAMP   NOT NULL,
    ends_at         TIMESTAMP   NOT NULL,
    party_size      INT         NOT NULL,
    status          VARCHAR(20) NOT NULL,
    notes           VARCHAR(300),
    created_at      TIMESTAMP   NOT NULL,
    version         BIGINT      NOT NULL DEFAULT 0
);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL REFERENCES users (id),
    restaurant_id BIGINT        NOT NULL REFERENCES restaurants (id),
    booking_id    BIGINT        REFERENCES bookings (id),
    status        VARCHAR(20)   NOT NULL,
    total         NUMERIC(10,2) NOT NULL,
    notes         VARCHAR(300),
    created_at    TIMESTAMP     NOT NULL,
    version       BIGINT        NOT NULL DEFAULT 0
);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    menu_item_id BIGINT        REFERENCES menu_items (id) ON DELETE SET NULL,
    name         VARCHAR(120)  NOT NULL,
    unit_price   NUMERIC(10,2) NOT NULL,
    quantity     INT           NOT NULL
);

CREATE INDEX idx_dining_tables_restaurant ON dining_tables (restaurant_id);
CREATE INDEX idx_menu_items_restaurant    ON menu_items (restaurant_id);
CREATE INDEX idx_bookings_table_time      ON bookings (dining_table_id, starts_at);
CREATE INDEX idx_bookings_restaurant_time ON bookings (restaurant_id, starts_at);
CREATE INDEX idx_bookings_user_time       ON bookings (user_id, starts_at);
CREATE INDEX idx_orders_user              ON orders (user_id);
CREATE INDEX idx_orders_restaurant        ON orders (restaurant_id);
CREATE INDEX idx_order_items_order        ON order_items (order_id);
